let source = readFileSync(file, 'utf8')
const missed = []
let replaced = 0
for (const [zh, ru] of Object.entries(map)) {
  const needle = JSON.stringify(zh)
  const replacement = JSON.stringify(ru)
  if (!source.includes(needle)) { missed.push(zh); continue }
  const count = source.split(needle).length - 1
  replaced += count
  source = source.split(needle).join(replacement)
}
writeFileSync(file, source)
console.log(`заменено вхождений: ${replaced}`)
if (missed.length > 0) {
  console.log('НЕ НАЙДЕНЫ в файле:')
  for (const item of missed) console.log(' -', JSON.stringify(item))
}
const left = source.match(/"[^"\n]*[\u4e00-\u9fa5][^"\n]*"/g) ?? []
console.log('осталось китайских литералов:', new Set(left).size)
for (const item of [...new Set(left)].slice(0, 20)) console.log('  ·', item)
